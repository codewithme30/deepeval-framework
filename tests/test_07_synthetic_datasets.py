# 3. Synthetic data (these spend tokens: capped by config)
# ======================================================================================
@pytest.mark.slow
def test_synthesizer_generates_goldens_from_policy_documents(metric_factory, max_goldens):
    """Reads real policy files, picks a few passages (contexts) and writes questions about them."""
    synthesizer = Synthesizer(model=metric_factory.judge, async_mode=False)
    documents = sorted(str(p) for p in POLICIES_DIR.glob("*.md"))[:2]  # two documents are plenty
    goldens = synthesizer.generate_goldens_from_docs(
        document_paths=documents,
        include_expected_output=True,
        max_goldens_per_context=1,
        context_construction_config=ContextConstructionConfig(
            critic_model=metric_factory.judge,
            max_contexts_per_document=1,
        ),
    )[:max_goldens]
    assert 1 <= len(goldens) <= max_goldens
    assert all(g.input.strip() for g in goldens)
    assert all(g.expected_output for g in goldens)


@pytest.mark.slow
def test_synthesizer_generates_goldens_from_scratch(metric_factory, max_goldens):
    """No documents: the LLM invents questions in the style we describe."""
    synthesizer = Synthesizer(
        model=metric_factory.judge,
        async_mode=False,
        styling_config=StylingConfig(
            scenario="A customer asks an insurance claims assistant about their auto or home policy.",
            task="Answer questions about deductibles, exclusions and the claims process.",
            input_format="One short customer question.",
            expected_output_format="One or two factual sentences.",
        ),
    )
    goldens = synthesizer.generate_goldens_from_scratch(num_goldens=max_goldens)
    assert 1 <= len(goldens) <= max_goldens
    assert all(g.input.strip() for g in goldens)


@pytest.mark.slow
def test_synthesizer_generates_multi_turn_goldens_from_scratch(metric_factory, max_goldens):
    synthesizer = Synthesizer(
        model=metric_factory.judge,
        async_mode=False,
        conversational_styling_config=ConversationalStylingConfig(
            scenario_context="A customer chats with an insurance claims assistant about an auto or home claim.",
            conversational_task="Help the customer understand their policy and the claims process.",
            participant_roles="A policyholder and a polite claims assistant.",
        ),
    )
    goldens = synthesizer.generate_conversational_goldens_from_scratch(num_goldens=max_goldens)
    assert 1 <= len(goldens) <= max_goldens
    assert all(isinstance(g, ConversationalGolden) and g.scenario for g in goldens)


