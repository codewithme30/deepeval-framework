"""
FEATURE: Datasets and synthetic data
====================================

WHAT IT IS
    A "golden" is one trusted example: a question plus (optionally) the ideal answer and the
    facts it should rest on. An EvaluationDataset is a collection of goldens. The workflow:

        goldens  --(run OUR app on each question)-->  test cases  --(metrics)-->  scores

    Goldens can be written by hand, loaded from JSON/CSV, pulled from the Confident AI
    dashboard, or GENERATED by DeepEval's Synthesizer from your own documents.

WHY IT MATTERS
    One test is an anecdote; a dataset is evidence. Synthetic generation bootstraps a large,
    varied test set from your policy documents in minutes instead of weeks of manual writing.
    Re-running the same dataset after every change shows whether quality went up or down.

WHAT THESE TESTS PROVE
    * Goldens load from data/datasets/goldens.json and goldens.csv (and can be added by hand).
    * Multi-turn (conversational) goldens load from conversations.json.
    * Goldens become test cases by running the app, then are scored two ways: pytest
      parametrisation with `assert_test` (one test per golden) and `evals_iterator` (one run).
    * The Synthesizer generates goldens from the policy documents and from scratch, capped by
      config/settings.yaml (`limits.max_goldens`, override with --max-goldens) to control cost.
    * Optional Confident AI push/pull, skipped unless CONFIDENT_API_KEY is set.

HOW TO READ PASS / FAIL
    Each golden is its own pytest test, so one bad row shows up by name. The xfail rows are
    goldens whose stub answer is wrong on purpose (an irrelevant roadside answer).

HOW TO RUN
    pytest -m dataset
    pytest -m dataset --max-goldens 2        # cap synthetic generation even lower
"""
import os

import pytest
from deepeval import assert_test
from deepeval.dataset import ConversationalGolden, EvaluationDataset, Golden
from deepeval.synthesizer import Synthesizer
from deepeval.synthesizer.config import ContextConstructionConfig, ConversationalStylingConfig, StylingConfig

from framework.config_loader import load_config
from framework.evals_runner import run_trace_evals
from framework.test_case_builders import golden_to_test_case

pytestmark = pytest.mark.dataset

_CONFIG = load_config()
DATASETS_DIR = _CONFIG.path("paths.datasets_dir")
POLICIES_DIR = _CONFIG.path("paths.policies_dir")


def _json_goldens() -> list[Golden]:
    dataset = EvaluationDataset()
    dataset.add_goldens_from_json_file(file_path=str(DATASETS_DIR / "goldens.json"))
    return dataset.goldens


# One pytest test per golden. The first is also tagged smoke. The last row is BAD ON PURPOSE.
BAD_GOLDEN = Golden(
    input="How much does roadside assistance cover?",
    expected_output="Roadside assistance covers towing up to 15 miles, jump-starts, flat tires and lockouts.",
)
GOLDEN_PARAMS = [
    pytest.param(g, id=g.input[:40], marks=[pytest.mark.smoke] if i == 0 else [])
    for i, g in enumerate(_json_goldens())
] + [
    pytest.param(
        BAD_GOLDEN,
        id="roadside-BAD",
        marks=pytest.mark.xfail(
            strict=True,
            raises=AssertionError,
            reason="demonstrates one bad row in a dataset run: the stub answers the roadside question with company history",
        ),
    )
]


# ======================================================================================
# 1. Loading and building datasets (no judge needed)
# ======================================================================================
@pytest.mark.smoke
@pytest.mark.no_judge
def test_goldens_load_from_json_file():
    goldens = _json_goldens()
    assert len(goldens) == 6
    assert all(g.input and g.expected_output and g.context for g in goldens)


@pytest.mark.no_judge
def test_goldens_load_from_csv_file():
    dataset = EvaluationDataset()
    dataset.add_goldens_from_csv_file(file_path=str(DATASETS_DIR / "goldens.csv"))
    assert len(dataset.goldens) == 4
    assert all(g.input and g.expected_output for g in dataset.goldens)


@pytest.mark.no_judge
def test_golden_can_be_added_by_hand():
    dataset = EvaluationDataset()
    dataset.add_golden(Golden(input="Do you cover hail damage?", expected_output="Yes, comprehensive coverage includes hail."))
    assert [g.input for g in dataset.goldens] == ["Do you cover hail damage?"]


@pytest.mark.no_judge
def test_multi_turn_goldens_load_from_conversations_file():
    """Conversational goldens describe a SCENARIO and a user; the simulator turns them into chats (test_06)."""
    dataset = EvaluationDataset()
    dataset.add_goldens_from_json_file(file_path=str(DATASETS_DIR / "conversations.json"))
    assert len(dataset.goldens) == 2
    assert all(isinstance(g, ConversationalGolden) for g in dataset.goldens)
    assert all(g.scenario and g.expected_outcome for g in dataset.goldens)


@pytest.mark.no_judge
def test_running_the_app_turns_a_golden_into_a_test_case(rag_app):
    golden = _json_goldens()[0]
    test_case = golden_to_test_case(rag_app, golden)
    assert test_case.input == golden.input
    assert test_case.expected_output == golden.expected_output  # the ideal answer travels with it
    assert test_case.actual_output and test_case.retrieval_context  # what OUR app produced and retrieved


# ======================================================================================
# 2. Evaluating a whole dataset: two styles
# ======================================================================================
@pytest.mark.parametrize("golden", GOLDEN_PARAMS)
def test_each_golden_gets_a_relevant_answer(rag_app, metric_factory, golden):
    """Style 1: one pytest test per golden, so a failure names the exact question."""
    metric = metric_factory.build("answer_relevancy", threshold=metric_factory.threshold("dataset_answer_relevancy"))
    assert_test(golden_to_test_case(rag_app, golden), [metric])


def test_whole_dataset_scores_in_one_evals_iterator_run(rag_app, sample_dataset, metric_factory, eval_kwargs):
    """Style 2: loop once with `dataset.evals_iterator(...)` and let DeepEval score every trace.
    (run_trace_evals uses evals_iterator under plain pytest and assert_test(golden=...) under
    `deepeval test run`; see framework/evals_runner.py for why.)"""
    metric = metric_factory.build("answer_relevancy", threshold=metric_factory.threshold("dataset_answer_relevancy"))
    run_trace_evals(sample_dataset, rag_app.query, metrics=[metric], **eval_kwargs)


@pytest.mark.xfail(
    strict=True,
    raises=AssertionError,
    reason="demonstrates an evals_iterator run failing because one golden in the dataset has a bad answer",
)
def test_dataset_run_fails_when_one_golden_is_answered_badly(rag_app, sample_dataset, metric_factory, eval_kwargs):
    sample_dataset.add_golden(BAD_GOLDEN)
    metric = metric_factory.build("answer_relevancy", threshold=metric_factory.threshold("dataset_answer_relevancy"))
    run_trace_evals(sample_dataset, rag_app.query, metrics=[metric], **eval_kwargs)


